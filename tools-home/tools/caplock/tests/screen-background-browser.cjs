const assert=require('node:assert/strict'),fs=require('node:fs');
module.exports=async(browser,base)=>{
 const context=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true}),page=await context.newPage(),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto(base);
 await page.locator('#videoFile').setInputFiles('/tmp/caplock-fixtures/key-bed.mp4');
 await page.waitForFunction(()=>document.querySelector('#status').textContent.includes('Source loaded'));
 await page.locator('#overlayFile').setInputFiles('/tmp/caplock-fixtures/phone-screen.mp4');
 await page.waitForFunction(()=>document.querySelectorAll('.media-layer').length===1);
 await page.locator('#clipTimeline .item-open').first().click();
 for(const [id,value] of [['clipWidth','100'],['clipX','50'],['clipY','50']])await page.locator('#'+id).fill(value);
 await page.locator('#applyClip').click();
 await page.locator('#captionBackground summary').click();
 await page.locator('#chromaTransparent').click();
 const pixels=()=>page.locator('.keyed-frame').evaluate(c=>{
  const ctx=c.getContext('2d'),at=(x,y)=>[...ctx.getImageData(x,y,1,1).data];
  return {screen:at(65,140),finger:at(100,220),camera:at(90,66),room:at(15,15)};
 });
 let preview=await pixels();
 assert.equal(preview.screen[3],0,'Transparent finds the internal green screen');
 for(const part of ['finger','camera','room'])assert.equal(preview[part][3],255,part+' stays opaque');
 await page.locator('#chromaKeep').click();
 assert.equal(await page.locator('.media-layer video').isVisible(),true);
 await page.locator('#chromaTransparent').click();
 await page.locator('#chromaBlue').click();
 assert.equal((await pixels()).screen[3],255,'the wrong key reproduces the owner report');
 await page.locator('#chromaGreen').click();
 assert.equal((await pixels()).screen[3],0,'Green screen repairs an existing wrong blue key');
 assert.equal(await page.locator('#chromaOpacity').inputValue(),'0');
 const draft=await page.evaluate(()=>JSON.parse(localStorage.getItem('gs_caplock_draft_v1')));
 assert.equal(draft.clips[0].chroma.color,'#00dd00');
 const exported=await page.evaluate(async({bedBytes,clipBytes,project})=>{
  const {renderCaptioned}=await import('/tools-home/tools/caplock/composite.mjs?v=38');
  const m=await import('/tools-home/tools/sxlock/vendor/mediabunny-1.62.1-gs1.mjs');
  const result=await renderCaptioned({project,bed:new Blob([new Uint8Array(bedBytes)]),readAsset:async()=>new Blob([new Uint8Array(clipBytes)])});
  const input=new m.Input({formats:m.ALL_FORMATS,source:new m.BlobSource(result.blob)}),track=await input.getPrimaryVideoTrack();
  const sample=await new m.VideoSampleSink(track).getSample(.04),canvas=document.createElement('canvas');canvas.width=180;canvas.height=320;
  const ctx=canvas.getContext('2d'),vf=sample.toVideoFrame();ctx.drawImage(vf,0,0);vf.close();sample.close();
  const at=(x,y)=>[...ctx.getImageData(x,y,1,1).data];input.dispose();
  return {frames:result.report.outputFrames,screen:at(65,140),finger:at(100,220),camera:at(90,66),room:at(15,15)};
 },{bedBytes:[...fs.readFileSync('/tmp/caplock-fixtures/key-bed.mp4')],clipBytes:[...fs.readFileSync('/tmp/caplock-fixtures/phone-screen.mp4')],project:draft});
 const near=(actual,expected)=>expected.every((v,i)=>Math.abs(actual[i]-v)<15);
 assert.equal(exported.frames,25);
 assert.ok(near(exported.screen,[34,51,68]),JSON.stringify(exported));
 assert.ok(near(exported.finger,[210,150,110]),JSON.stringify(exported));
 assert.ok(near(exported.camera,[0,0,0]),JSON.stringify(exported));
 assert.ok(near(exported.room,[160,100,50]),JSON.stringify(exported));
 await page.locator('#closeClipProperties').click();
 await page.locator('#layerUndo').click();
 assert.equal((await pixels()).screen[3],255);
 await page.locator('#layerRedo').click();
 assert.equal((await pixels()).screen[3],0);
 const recovery=new URL(base);recovery.searchParams.set('recover','local');
 await page.goto(recovery.href);
 await page.waitForFunction(()=>document.querySelectorAll('#clipTimeline .item-open').length===1);
 const restored=await page.evaluate(()=>JSON.parse(localStorage.getItem('gs_caplock_draft_v1')));
 assert.equal(restored.clips[0].chroma.color,'#00dd00');
 assert.equal(restored.clips[0].chroma.backgroundOpacity,0);
 assert.deepEqual(errors,[]);
 console.log(JSON.stringify({screenBackground:true,preview,exported,undoRedo:true,recovery:true}));
 await context.close();
};
