import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import ts from 'typescript';
const reportSource=await fs.readFile(new URL('../app/report.ts',import.meta.url),'utf8');
const reportJS=ts.transpileModule(reportSource,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ES2022}}).outputText;
const reportURL='data:text/javascript;base64,'+Buffer.from(reportJS).toString('base64');
let source=await fs.readFile(new URL('../app/jokelab.ts',import.meta.url),'utf8');
source=source.replace("'./report'",JSON.stringify(reportURL));
const js=ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ES2022}}).outputText;
const {buildPrompt,defaults,validateRecord,PROMPT_VERSION}=await import('data:text/javascript;base64,'+Buffer.from(js).toString('base64'));
const joke='Why couldn’t it stand?\n“It’s obviously too tired.”';
const notes='Try “allegedly” at the END.\nNo extra line after the payoff.';
const settings={...defaults,tense:'Past tense',customTone:'quietly skeptical',count:5};
const prompt=buildPrompt(joke,notes,settings,null,'test-run');
assert(prompt.includes(JSON.stringify(joke)),'Exact source preserved, including newlines and curly punctuation');
assert(prompt.includes(notes),'Scribe included verbatim');
assert(prompt.includes('Past tense')&&prompt.includes('quietly skeptical'),'Tense and custom tone included');
assert(prompt.includes('5 separately numbered')&&prompt.includes('five')===false,'Requested batch count included');
assert(prompt.includes('voice pace')&&prompt.includes('video gaze')&&prompt.includes('STOP SPEAKING'),'Tone carries into performance');
assert.throws(()=>buildPrompt('   ',notes,settings));
const next=buildPrompt(joke,notes+' changed',settings,null,'next-run');
assert(next!==prompt&&next.includes(notes+' changed'),'New input produces new prompt');
const r={id:crypto.randomUUID(),kind:'cluster',name:'Bicycle — allegedly',prompt,text:joke,notes,status:'CLUSTER',createdAt:new Date().toISOString(),parentId:null,settings,card:null,promptVersion:PROMPT_VERSION};
assert.deepEqual(validateRecord(JSON.parse(JSON.stringify(r))),r,'Complete named cluster survives JSON roundtrip');
assert.throws(()=>validateRecord({...r,name:' '}),'Reject unnamed clusters');
assert.throws(()=>validateRecord({...r,prompt:''}),'Reject missing prompt');
assert.throws(()=>validateRecord({...r,settings:{...settings,count:500}}),'Reject invalid batch count');
assert.throws(()=>validateRecord({...r,text:'x'.repeat(150001)}),'Bound record content');
const revision=validateRecord({...r,id:crypto.randomUUID(),parentId:r.id,notes:'Next revision'});
assert.equal(revision.parentId,r.id);assert.equal(r.notes,notes,'Earlier version unchanged');
console.log('PASS: exact text, Scribe, tone/tense, count, performance continuity, empty input, changed input, cluster roundtrip, naming, content bounds, revision parent.');

const {encodePayload,decodePayload,validateReport}=await import(reportURL);
const report={schema:'JokeReport-1.0',id:'test-report',name:'Unicode report',source:joke,notes,variants:[{id:'v1',text:joke,tone:'Mock certainty',tense:'Past tense',qualifier:'obviously',notes}]};
assert.deepEqual(validateReport(await decodePayload(encodePayload(report))),report,'Unicode report survives link encoding');
const {deflateSync}=await import('node:zlib');
assert.deepEqual(await decodePayload(deflateSync(JSON.stringify(report)).toString('base64url'),true),report,'Compressed report link roundtrip');
assert.throws(()=>validateReport({...report,variants:[report.variants[0],report.variants[0]]}),'Duplicate variant IDs rejected');
assert.deepEqual(validateRecord({...r,report}).report,report,'Named cluster retains entire report');
const longform=buildPrompt(joke,notes,{...settings,stage:'longform'});
assert(longform.includes('Develop 5 long-form jokes')&&!longform.includes('WORDING LOCK:'),'Long-form can expand the seed');
console.log('PASS: Unicode and compressed report handoff, variant validation, report retention, long-form request.');
